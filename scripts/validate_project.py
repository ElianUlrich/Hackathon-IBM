"""
validate_project.py — PinPilot project file validator.
Generated by PinPilot. Source: docs/PROJECT_PINPILOT.md §8.
Usage: python scripts/validate_project.py <project.json>
Exit code: 0 = valid (no errors; warnings may be present), 1 = errors found, 2 = bad arguments/missing file.
"""

import argparse
import json
import sys
from pathlib import Path

# ---------------------------------------------------------------------------
# Paths (all relative to repository root)
# ---------------------------------------------------------------------------
REPO_ROOT = Path(__file__).parent.parent
SCHEMA_DIR = REPO_ROOT / "schema"
CATALOG_DIR = REPO_ROOT / "catalog"

# ---------------------------------------------------------------------------
# Lazy import: jsonschema is a dependency declared in requirements.txt
# ---------------------------------------------------------------------------
try:
    import jsonschema
except ImportError:
    print("ERROR: jsonschema is not installed. Run: pip install jsonschema>=4.0", file=sys.stderr)
    sys.exit(2)


# ---------------------------------------------------------------------------
# Helpers
# ---------------------------------------------------------------------------

def load_json(path: Path) -> dict:
    try:
        with path.open(encoding="utf-8") as f:
            return json.load(f)
    except (OSError, json.JSONDecodeError) as exc:
        print(f"ERROR: Cannot load {path}: {exc}", file=sys.stderr)
        sys.exit(2)


def load_catalog_component(catalog_id: str) -> dict | None:
    """Return the catalog entry for catalog_id, or None if not found."""
    entry_path = CATALOG_DIR / "components" / f"{catalog_id}.json"
    if not entry_path.exists():
        return None
    return load_json(entry_path)


def load_pin_table() -> dict:
    return load_json(CATALOG_DIR / "esp32_devkit_pins.json")


FLASH_PINS = set(range(6, 12))          # GPIO6–11
INPUT_ONLY_PINS = {34, 35, 36, 39}     # GPIO37/38 not broken out on WROOM-32/DevKit
STRAPPING_PINS = {0, 2, 5, 12, 15}
UART0_PINS = {1, 3}
# GPIO37 and GPIO38 exist on the die but are NOT broken out on WROOM-32/DevKit boards.
EXISTING_GPIOS = set(range(0, 20)) | {21, 22, 23} | set(range(25, 28)) | {32, 33, 34, 35, 36, 39}


# ---------------------------------------------------------------------------
# Stage 1: JSON Schema validation
# ---------------------------------------------------------------------------

def validate_schema(project: dict) -> list[str]:
    """Return a list of schema-level error messages (empty = OK)."""
    schema_path = SCHEMA_DIR / "project.schema.json"
    schema = load_json(schema_path)
    validator = jsonschema.Draft7Validator(schema)
    errors = []
    for err in sorted(validator.iter_errors(project), key=lambda e: list(e.path)):
        path = " > ".join(str(p) for p in err.path) or "(root)"
        errors.append(f"Schema error at {path}: {err.message}")
    return errors


